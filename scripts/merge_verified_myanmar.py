#!/usr/bin/env python3
"""Fail-closed, incremental import of human-reviewed Myanmar Tipitaka content.

The current source SQLite schema uses paragraphs.id (integer), not segment_id.
CSV segment_id therefore accepts that stable paragraph ID, or an actual
segment_id column if a future database provides one. No text or approval is
generated by this script.
"""
import argparse, csv, datetime, hashlib, json, pathlib, sqlite3, sys

COLUMNS={"segment_id","content_type","text_my","source_ref","rights_evidence",
         "reviewer_1","reviewer_2","review_reference","reviewed_at","source_pali_sha256"}
KINDS={"translation","explanation"}

def digest(value):
    return hashlib.sha256(value.encode("utf-8")).hexdigest()

def table_columns(db, table):
    return {r[1] for r in db.execute(f"PRAGMA table_info({table})")}

def create_table(db):
    db.executescript("""
    CREATE TABLE IF NOT EXISTS paragraph_myanmar_content(
      paragraph_id INTEGER NOT NULL,
      segment_id TEXT NOT NULL,
      content_type TEXT NOT NULL CHECK(content_type IN ('translation','explanation')),
      text_my TEXT NOT NULL,
      source_ref TEXT NOT NULL,
      rights_evidence TEXT NOT NULL,
      reviewer_1 TEXT NOT NULL,
      reviewer_2 TEXT NOT NULL,
      review_reference TEXT NOT NULL,
      reviewed_at TEXT NOT NULL,
      source_pali_sha256 TEXT NOT NULL,
      reviewed INTEGER NOT NULL CHECK(reviewed=1),
      PRIMARY KEY(paragraph_id,content_type)
    );
    CREATE INDEX IF NOT EXISTS idx_pmc_type ON paragraph_myanmar_content(content_type,paragraph_id);
    """)

def resolve_paragraph(db, identifier, cols):
    if "segment_id" in cols:
        row=db.execute("SELECT id,body FROM paragraphs WHERE segment_id=?",(identifier,)).fetchone()
        if row:return row
    if identifier.isdigit():
        return db.execute("SELECT id,body FROM paragraphs WHERE id=?",(int(identifier),)).fetchone()
    return None

def import_rows(db, csv_path):
    counts={"translation":0,"explanation":0}
    if not csv_path.is_file():
        return counts
    cols=table_columns(db,"paragraphs")
    with csv_path.open(encoding="utf-8-sig",newline="") as fh:
        reader=csv.DictReader(fh)
        missing=COLUMNS-set(reader.fieldnames or [])
        if missing: raise ValueError("Missing reviewed CSV columns: "+", ".join(sorted(missing)))
        seen=set()
        for line,row in enumerate(reader,2):
            v={k:(row.get(k) or "").strip() for k in COLUMNS}
            if any(not x for x in v.values()):
                raise ValueError(f"Row {line}: missing required review, rights, text or source field")
            if v["content_type"] not in KINDS:
                raise ValueError(f"Row {line}: content_type must be translation or explanation")
            if v["reviewer_1"].casefold()==v["reviewer_2"].casefold():
                raise ValueError(f"Row {line}: two distinct reviewers are required")
            try: reviewed=datetime.date.fromisoformat(v["reviewed_at"])
            except ValueError: raise ValueError(f"Row {line}: reviewed_at must be YYYY-MM-DD")
            if reviewed>datetime.date.today():
                raise ValueError(f"Row {line}: review date cannot be in the future")
            key=(v["segment_id"],v["content_type"])
            if key in seen: raise ValueError(f"Row {line}: duplicate segment/type in CSV")
            seen.add(key)
            found=resolve_paragraph(db,v["segment_id"],cols)
            if not found: raise ValueError(f"Row {line}: Pali paragraph not found: {v['segment_id']}")
            pid,pali=found
            if digest(pali)!=v["source_pali_sha256"].lower():
                raise ValueError(f"Row {line}: Pali SHA-256 mismatch: {v['segment_id']}")
            db.execute("""INSERT INTO paragraph_myanmar_content
              (paragraph_id,segment_id,content_type,text_my,source_ref,rights_evidence,
               reviewer_1,reviewer_2,review_reference,reviewed_at,source_pali_sha256,reviewed)
              VALUES(?,?,?,?,?,?,?,?,?,?,?,1)
              ON CONFLICT(paragraph_id,content_type) DO UPDATE SET
               segment_id=excluded.segment_id,text_my=excluded.text_my,
               source_ref=excluded.source_ref,rights_evidence=excluded.rights_evidence,
               reviewer_1=excluded.reviewer_1,reviewer_2=excluded.reviewer_2,
               review_reference=excluded.review_reference,reviewed_at=excluded.reviewed_at,
               source_pali_sha256=excluded.source_pali_sha256,reviewed=1""",
              (pid,v["segment_id"],v["content_type"],v["text_my"],v["source_ref"],
               v["rights_evidence"],v["reviewer_1"],v["reviewer_2"],
               v["review_reference"],v["reviewed_at"],v["source_pali_sha256"]))
            # Maintain compatibility with the existing offline explanation popup.
            if v["content_type"]=="explanation" and "paragraph_explanations" in {
                r[0] for r in db.execute("SELECT name FROM sqlite_master WHERE type='table'")}:
                exp_cols=table_columns(db,"paragraph_explanations")
                required={"paragraph_id","language","explanation_my","source_ref","provenance","reviewed"}
                if required.issubset(exp_cols):
                    db.execute("""INSERT INTO paragraph_explanations
                      (paragraph_id,language,explanation_my,source_ref,provenance,reviewed)
                      VALUES(?,'my',?,?,'editorial_explanation',1)
                      ON CONFLICT(paragraph_id,language) DO UPDATE SET
                      explanation_my=excluded.explanation_my,source_ref=excluded.source_ref,
                      provenance=excluded.provenance,reviewed=1""",
                      (pid,v["text_my"],v["source_ref"]))
            counts[v["content_type"]]+=1
    return counts

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--database",type=pathlib.Path,default=pathlib.Path("app/src/main/assets/tipitaka_offline.sqlite"))
    ap.add_argument("--reviewed",type=pathlib.Path,default=pathlib.Path("corpus/reviewed_myanmar.csv"))
    ap.add_argument("--report",type=pathlib.Path,default=pathlib.Path("myanmar_review_coverage.json"))
    args=ap.parse_args()
    if not args.database.is_file(): sys.exit("Offline Pali SQLite missing; no Myanmar content imported.")
    db=sqlite3.connect(args.database)
    try:
        if not {"id","body"}.issubset(table_columns(db,"paragraphs")):
            sys.exit("Unsupported paragraphs schema: expected id and body columns.")
        create_table(db)
        # The Android reader joins review rows by paragraphs.segment_id.
        # Legacy schema uses integer paragraphs.id, so add a stable text alias.
        pcols=table_columns(db,"paragraphs")
        if "segment_id" not in pcols:
            db.execute("ALTER TABLE paragraphs ADD COLUMN segment_id TEXT")
        db.execute("UPDATE paragraphs SET segment_id=CAST(id AS TEXT) WHERE segment_id IS NULL OR trim(segment_id)=''")
        with db:
            imported=import_rows(db,args.reviewed)
        total=db.execute("SELECT COUNT(*) FROM paragraphs").fetchone()[0]
        stats=dict(db.execute("SELECT content_type,COUNT(*) FROM paragraph_myanmar_content WHERE reviewed=1 GROUP BY content_type"))
        both=db.execute("""SELECT COUNT(*) FROM paragraphs p
          WHERE EXISTS(SELECT 1 FROM paragraph_myanmar_content x WHERE x.paragraph_id=p.id AND x.content_type='translation' AND x.reviewed=1)
          AND EXISTS(SELECT 1 FROM paragraph_myanmar_content y WHERE y.paragraph_id=p.id AND y.content_type='explanation' AND y.reviewed=1)""").fetchone()[0]
        report={"pali_paragraphs_total":total,"reviewed_myanmar_translations":stats.get("translation",0),
          "reviewed_myanmar_explanations":stats.get("explanation",0),"paragraphs_with_both":both,
          "reviewed_import_file_supplied":args.reviewed.is_file(),"imported_this_run":imported,
          "all_paragraphs_have_translation":stats.get("translation",0)==total,
          "all_paragraphs_have_explanation":stats.get("explanation",0)==total,
          "approval_rule":"two distinct named reviewers, rights evidence, source reference, review record and matching original Pali SHA-256"}
        args.report.parent.mkdir(parents=True,exist_ok=True)
        args.report.write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
        print(json.dumps(report,ensure_ascii=False,indent=2))
    finally: db.close()

if __name__=="__main__": main()
